/**
 * Enriches a database post object with the corresponding pre-written car article content.
 * Matches based on the post's articleIndex.
 */
export function enrichPost(post) {
  if (!post) return null;
  
  // Handle Mongoose documents by converting to JSON if necessary
  const postObj = typeof post.toJSON === "function" ? post.toJSON() : { ...post };
  
  const index = postObj.articleIndex !== undefined ? postObj.articleIndex : 0;
  const article = carArticles[index % carArticles.length];
  
  return {
    ...postObj,
    title: article.title,
    category: article.category,
    blurb: article.blurb,
    contentPart1: article.contentPart1,
    contentPart2: article.contentPart2,
    content: `${article.contentPart1}\n<!-- PROMPT_BOX -->\n${article.contentPart2}`
  };
}

/**
 * Converts a text string into a URL-friendly slug.
 */
export function slugify(text) {
  if (!text) return "";
  return text
    .toString()
    .toLowerCase()
    .trim()
    .replace(/\s+/g, "-")          // Replace spaces with -
    .replace(/[^\w\-]+/g, "")       // Remove all non-word chars
    .replace(/\-\-+/g, "-")         // Replace multiple - with single -
    .replace(/^-+/, "")             // Trim - from start
    .replace(/-+$/, "");            // Trim - from end
}

/**
 * Returns an SEO-friendly slug for a post, combining the title and the post's database ID.
 */
export function getPostSlug(post) {
  if (!post) return "";
  const titleSlug = slugify(post.title || "car-review");
  const id = post.id || post._id?.toString() || "";
  return titleSlug ? `${titleSlug}-${id}` : id;
}
